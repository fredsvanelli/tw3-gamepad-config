export const STRINGS: Record<Locale, Strings> = { en, pt, es }

export function detectLocale(): Locale {
  const languages = typeof navigator === 'undefined' ? [] : navigator.languages ?? [navigator.language]
  for (const language of languages) {
    const base = language.toLowerCase().slice(0, 2)
    if (base === 'pt' || base === 'es' || base === 'en') return base
  }
  return 'en'
}

/** Lower rank wins when a Conflict happens in several Game Contexts. */
export function contextRank(context: string): number {
  const order = Object.keys(en.contexts)
  const i = order.indexOf(context)
  return i === -1 ? order.length : i
}

export function contextLabel(strings: Strings, context: string): string {
  return strings.contexts[context] ?? context
}
